export function t(lang, key, vars) {
  const dict = T[lang] || T.es;
  let str = dict[key] ?? T.es[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replaceAll(`{${k}}`, String(v));
    }
  }
  return str;
}
